// Bundles the code main runs in web pages, from src/page, into src/main/pageCode.ts. Each export of src/page/index.ts
// becomes one function expression with only what it uses, and main calls it with its arguments as JSON, so no value is
// ever written into the code. `pnpm run page:build` writes the file. With `--check` it only fails if the file isn't what
// this would write, which `electron-vite build` and `pnpm run runner:build` run first.
import { build, transform } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const INDEX = "src/page/index.ts";
const OUT = "src/main/pageCode.ts";

// Electron's Chromium and the cloud's Chrome run anything new, so nothing is rewritten for an older browser.
const printing = { target: "esnext", charset: "utf8", legalComments: "none", logLevel: "silent" };
const options = { ...printing, absWorkingDir: root, bundle: true, write: false, format: "esm", platform: "browser" };

// Each entry is bundled from the module it's in, not through the index, which would bring every module's top-level code.
const index = readFileSync(join(root, INDEX), "utf8").replace(/\r\n/g, "\n");
const reexport = /^export \{([^}]+)\} from "\.\/([\w/]+)";$/gm;
const sources = [...index.matchAll(reexport)].flatMap(([, list, from]) =>
  list
    .split(",")
    .map((name) => name.trim())
    .filter(Boolean)
    .map((name) => ({ name, from: `src/page/${from}` })),
);
const statements = index
  .replace(/^\/\/.*$/gm, "")
  .replace(reexport, "")
  .trim();
if (statements) throw new Error(`${INDEX} may only re-export by name, but has: ${statements.split("\n")[0]}`);
sources.sort((a, b) => (a.name < b.name ? -1 : 1));

const bundle = async ({ name, from }) => {
  const { outputFiles, metafile } = await build({
    ...options,
    metafile: true,
    stdin: { contents: `export { ${name} as default } from "./${from}";`, resolveDir: root, sourcefile: `${name}.ts`, loader: "ts" },
  });
  // Lint stops most imports from outside src/page, and this stops the rest, at any depth, before any of it reaches a page.
  const outside = Object.keys(metafile.inputs).filter((input) => input !== `${name}.ts` && !input.startsWith("src/page/"));
  if (outside.length) throw new Error(`${name}: code that runs in a page may only come from src/page, but has ${outside.join(", ")}`);
  // Printed again, which drops the comments the bundler adds to name each source file, and only comments.
  const { code: text } = await transform(outputFiles[0].text, { ...printing, loader: "js", format: "esm" });
  const ending = /\nexport \{\n {2}(\w+) as default\n\};\n$/;
  const local = text.match(ending)?.[1];
  if (!local) throw new Error(`${name}: esbuild's output didn't end in the one default export this expects`);
  const body = text.replace(ending, "\n").trim();
  return `(() => {\n${body}\nreturn ${local};\n})()`;
};

const NOTE = `// Generated by scripts/buildPage.mjs from src/page. Don't edit this: change src/page and run \`pnpm run page:build\`.
// Each is a function expression for main to call with its arguments as JSON, through \`inPage\` in pageScripts.ts.

// The arguments are only in the type, so main can't call one with anything else.
export interface PageScript<Args> {
  readonly code: string;
  readonly takes?: (args: Args) => void;
}

type Entries = typeof import("../page/index");
// What a script takes: its one argument, or nothing.
type ArgsOf<F extends (...args: never[]) => unknown> = Parameters<F> extends [infer Args] ? Args : undefined;
`;

const entries = [];
for (const { name, from } of sources) {
  const code = await bundle({ name, from });
  entries.push(`export const ${name}: PageScript<ArgsOf<Entries[${JSON.stringify(name)}]>> = { code: ${JSON.stringify(code)} };`);
}
const text = `${NOTE}\n${entries.join("\n\n")}\n`;

const path = join(root, OUT);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Not there at all.
  }
  if (current !== text) {
    console.error(`${OUT} isn't what src/page builds to. Run \`pnpm run page:build\` and commit it.`);
    process.exit(1);
  }
} else {
  writeFileSync(path, text);
}
