// Writes what comes from the app: in site/, so the public page has the same drawing, the same words for permissions and
// the same checks on a row, and src/main/tools/pageActorArt.ts, for the mascot on web pages. Run with `pnpm run site:build` after
// changing any of them. With `--check` it writes nothing and fails if a text file isn't what it would write, which CI runs.
// The fonts and the share picture aren't checked: the fonts are copied as they are, and the picture depends on the Chrome
// that draws it.
import { build } from "esbuild";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The app's own import aliases, as in `electron.vite.config.ts`, so shared code reads the same here.
const alias = { "@shared": join(root, "src/shared"), "@common": join(root, "src/renderer/common") };
const site = join(root, "site");
const NOTE = "// Generated by scripts/buildSite.mjs. Don't edit this.\n";
const CHECK = process.argv.includes("--check");
const stale = [];
const lf = (text) => text.replace(/\r\n/g, "\n");
// Writes a generated text file, or with `--check` notes it if what's there is different.
const put = (file, text) => {
  if (!CHECK) return writeFileSync(file, text);
  let current = null;
  try {
    current = lf(readFileSync(file, "utf8"));
  } catch {
    // Not there at all.
  }
  if (current !== lf(text)) stale.push(relative(root, file).replaceAll("\\", "/"));
};

